// Build assets/presales.js (チケット先行タイムライン用) from raw GraphQL responses of https://calendar-bmsg.tokyo.
// 先行系 = 受付期間 (start_at〜end_at) を持ち、タイトル/サブタイトル/本文に先行・抽選・一般発売などを含む LIVE/Other の予定。
// usage: node tools/build_presales.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const raw = [];
for (const f of fs.readdirSync(path.join(root, 'data/raw')).filter(f => f.endsWith('.json')).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(root, 'data/raw', f), 'utf8'));
  const list = Array.isArray(j) ? j.flatMap(d => d.events_with_month || []) : (j.data?.events_with_month || []);
  raw.push(...list);
}

const strip = s => (s || '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
const KEYWORD = /先行|抽選|一般発売|先着販売|プレリクエスト|受付/;
const EXCLUDE_CAT = /RELEASE|TV|RADIO|MAGAZINE|BIRTHDAY|YOUTUBE/i;
const JST = 9 * 3600e3;
const jstIso = iso => new Date(new Date(iso).getTime() + JST).toISOString().slice(0, 16); // "2026-10-24T12:00" (JST)

// 「プレリクエスト先行受付中（抽選販売）」→「プレリクエスト先行（抽選）」
const kindOf = e => {
  const s = strip(e.sub_title) || '';
  return s.replace(/受付中/g, '').replace(/発売中/g, '発売').replace(/販売）/g, '）').replace(/\s+/g, ' ').trim();
};

const map = new Map(); // the site stores one row per artist for the same event
for (const e of raw) {
  if (!e.end_at || !e.start_at) continue;
  if (new Date(e.end_at) - new Date(e.start_at) < 3600e3) continue;       // 期間を持たないものは除外
  const cat = (e.event_category?.title_en || '').toUpperCase();
  if (EXCLUDE_CAT.test(cat)) continue;
  if (!KEYWORD.test(`${e.title} ${e.sub_title || ''} ${strip(e.content)}`)) continue;
  const key = `${e.start_at}|${e.end_at}|${e.title}`;
  const artists = e.event_artists.map(a => a.artist.name);
  if (map.has(key)) { const m = map.get(key); for (const a of artists) if (!m.artists.includes(a)) m.artists.push(a); continue; }
  map.set(key, {
    artists,
    title: e.title.replace(/[『』]/g, '').trim(),
    kind: kindOf(e),
    start: jstIso(e.start_at),
    end: jstIso(e.end_at),
    link: e.link_url || '',
    thumb: e.thumbnail_url || '',
  });
}
const list = [...map.values()].sort((a, b) => a.start.localeCompare(b.start));
const out = `// generated by tools/build_presales.mjs from calendar-bmsg.tokyo — ${list.length} presales\nwindow.PRESALES = ${JSON.stringify(list, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'assets/presales.js'), out);
console.log(list.length, 'presales');
for (const p of list) console.log(p.start, '→', p.end, p.artists.join('/'), p.title, '/', p.kind);
