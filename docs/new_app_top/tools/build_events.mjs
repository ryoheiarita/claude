// Build assets/events.js from raw GraphQL responses of https://calendar-bmsg.tokyo (/api/graphql, GetEvents).
// usage: node tools/build_events.mjs [fromISO=2026-09-29] [toISO=2026-11-30]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FROM = process.argv[2] || '2026-09-29';
const TO   = process.argv[3] || '2026-11-30';

const raw = [];
for (const f of fs.readdirSync(path.join(root, 'data/raw')).filter(f => f.endsWith('.json')).sort()) {
  const j = JSON.parse(fs.readFileSync(path.join(root, 'data/raw', f), 'utf8'));
  const list = Array.isArray(j) ? j.flatMap(d => d.events_with_month || []) : (j.data?.events_with_month || []);
  raw.push(...list);
}

const JST = 9 * 60;
const toJst = iso => new Date(new Date(iso).getTime() + JST * 60000); // shift so UTC getters read JST
const p2 = n => String(n).padStart(2, '0');
const dateKey = d => `${d.getUTCFullYear()}-${p2(d.getUTCMonth() + 1)}-${p2(d.getUTCDate())}`;
const hm = d => `${p2(d.getUTCHours())}:${p2(d.getUTCMinutes())}`;

// dedupe: the site stores one row per artist for the same event
const map = new Map();
for (const e of raw) {
  const s = toJst(e.start_at);
  const key = dateKey(s);
  if (key < FROM || key > TO) continue;
  const id = `${e.start_at}|${e.end_at || ''}|${e.title}`;
  const artists = e.event_artists.map(a => a.artist.name);
  if (map.has(id)) { const m = map.get(id); for (const a of artists) if (!m.artists.includes(a)) m.artists.push(a); if (!m.link && e.link_url) m.link = e.link_url; continue; }
  const en = e.end_at ? toJst(e.end_at) : null;
  // all-day: starts 00:00 JST and either has no end or ends 23:59 (the site stores day-long events this way)
  const allDay = s.getUTCHours() === 0 && s.getUTCMinutes() === 0 && (!en || (en.getUTCHours() === 23 && en.getUTCMinutes() === 59));
  map.set(id, {
    date: key,
    start: allDay ? '' : hm(s),
    end: en ? hm(en) : '',
    allDay,
    cat: (e.event_category?.title_en || e.event_category?.title || 'OTHER').toUpperCase(),
    artists,
    title: e.title.trim(),
    link: e.link_url || '',
    sort: e.start_at,
  });
}
// fictional extras (ライブ先行 / PPV / FC新規開設) kept in data/extra_events.json
const extraPath = path.join(root, 'data/extra_events.json');
const extras = fs.existsSync(extraPath) ? JSON.parse(fs.readFileSync(extraPath, 'utf8')).filter(e => e.date >= FROM && e.date <= TO) : [];
for (const e of extras) e.sort = `${e.date}T${e.start || '00:00'}`;
for (const e of map.values()) e.sort = `${e.date}T${e.start || '00:00'}`; // re-key in JST so extras interleave correctly
const events = [...map.values(), ...extras].sort((a, b) => a.sort.localeCompare(b.sort) || a.title.localeCompare(b.title, 'ja'));
for (const ev of events) delete ev.sort;

const out = `// generated by tools/build_events.mjs from calendar-bmsg.tokyo (${FROM} .. ${TO}) — ${events.length} events\nwindow.EVENTS = ${JSON.stringify(events, null, 1)};\n`;
fs.writeFileSync(path.join(root, 'assets/events.js'), out);
const cats = {}; for (const e of events) cats[e.cat] = (cats[e.cat] || 0) + 1;
console.log(events.length, 'events', cats);
console.log(events.slice(0, 5));
